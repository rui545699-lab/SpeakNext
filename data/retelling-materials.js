'use strict';

function keyPoint(id, role, text, displayText, semanticAnchors, feedbackText, expressionCue) {
  const value = { id, role, text };
  if (displayText) value.displayText = displayText;
  if (feedbackText) value.feedbackText = feedbackText;
  if (expressionCue) value.expressionCue = expressionCue;
  if (Array.isArray(semanticAnchors) && semanticAnchors.length) {
    value.semanticAnchors = Object.freeze(semanticAnchors.slice());
  }
  return Object.freeze(value);
}

function relation(id, from, to) {
  return Object.freeze({ id, from, to, type: 'CAUSE' });
}

function material({
  id,
  title,
  text,
  coreMessage,
  resultReference,
  missingHintQuestions,
  keyPoints
}) {
  return Object.freeze({
    id,
    title,
    text,
    coreMessage,
    resultReference,
    missingHintQuestions: Object.freeze(Object.assign({}, missingHintQuestions)),
    keyPoints: Object.freeze(keyPoints),
    relations: Object.freeze([
      relation('R1', 'K1', 'K2'),
      relation('R2', 'K2', 'K3')
    ])
  });
}

